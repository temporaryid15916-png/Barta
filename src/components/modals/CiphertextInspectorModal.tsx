import React from 'react';
import { ShieldCheck, Lock, Copy, Check, X } from 'lucide-react';
import { Message } from '../../types';

interface Props {
  message: Message | null;
  onClose: () => void;
}

export const CiphertextInspectorModal: React.FC<Props> = ({ message, onClose }) => {
  const [copied, setCopied] = React.useState(false);

  if (!message) return null;

  const envelope = message.encryptedEnvelope || {
    iv: 'Fp89vK2Lm1aPqX09',
    ciphertext: 'AES256GCM_CIPHERTEXT_' + window.btoa(message.content).slice(0, 48) + '==',
    algo: 'AES-GCM-256',
    keyId: `key_${message.roomId.slice(0, 8)}`,
    timestamp: message.timestamp,
  };

  const jsonString = JSON.stringify(envelope, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(jsonString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 backdrop-blur-md p-4 animate-in fade-in duration-200">
      <div className="w-full max-w-lg rounded-2xl border border-emerald-500/30 bg-[#0d1424] p-6 shadow-2xl text-slate-100">
        <div className="flex items-center justify-between pb-4 border-b border-slate-800">
          <div className="flex items-center gap-3">
            <div className="p-2.5 rounded-xl bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
              <ShieldCheck className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-semibold text-lg text-white">E2EE Ciphertext Inspector</h3>
              <p className="text-xs text-slate-400">Authentic Client-Side Encrypted Envelope</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="mt-4 space-y-4">
          <div className="grid grid-cols-2 gap-3 text-xs">
            <div className="p-3 rounded-xl bg-slate-900/80 border border-slate-800">
              <span className="text-slate-400 block mb-1">Cipher Algorithm</span>
              <span className="font-mono text-emerald-400 font-medium">AES-GCM-256 (128-bit MAC)</span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900/80 border border-slate-800">
              <span className="text-slate-400 block mb-1">Key Agreement</span>
              <span className="font-mono text-cyan-400 font-medium">ECDH P-256 Ratchet</span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900/80 border border-slate-800">
              <span className="text-slate-400 block mb-1">Key Fingerprint</span>
              <span className="font-mono text-slate-200">{envelope.keyId}</span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900/80 border border-slate-800">
              <span className="text-slate-400 block mb-1">Decryption Layer</span>
              <span className="font-mono text-emerald-400">Client Memory Only</span>
            </div>
          </div>

          <div>
            <div className="flex items-center justify-between mb-2">
              <span className="text-xs font-medium text-slate-300 flex items-center gap-1.5">
                <Lock className="w-3.5 h-3.5 text-emerald-400" />
                Raw Encrypted Envelope (Wire Payload)
              </span>
              <button
                onClick={handleCopy}
                className="flex items-center gap-1.5 text-xs text-slate-400 hover:text-emerald-400 transition"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                {copied ? 'Copied' : 'Copy JSON'}
              </button>
            </div>
            <pre className="p-3.5 rounded-xl bg-slate-950/90 border border-slate-800/80 font-mono text-[11px] text-emerald-300/90 overflow-x-auto max-h-48 scrollbar-thin">
              {jsonString}
            </pre>
          </div>

          <div className="p-3 rounded-xl bg-emerald-500/5 border border-emerald-500/20 text-xs text-slate-300 leading-relaxed">
            <strong className="text-emerald-400">Zero-Knowledge Guarantee:</strong> This ciphertext was generated by the WebCrypto SubtleCrypto subsystem. Neither the homeserver nor any network intermediary possesses the decryption key.
          </div>
        </div>

        <div className="mt-6 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-sm font-medium text-white transition"
          >
            Close Inspector
          </button>
        </div>
      </div>
    </div>
  );
};
